"""Branch name, commit message and PR title/body — provider-neutral text.

None of this knows a forge's syntax: issue references (``#N``,
``owner/repo#N``, ``!N``) and the auto-close line (``Closes #N``) are
formatted by the provider and passed in already rendered (PRD §3.2).
"""

from __future__ import annotations

import re

TRUNCATION_NOTE = "\n\n…(truncated)"


def fit_body(text: str, max_length: int) -> str:
    """Cut ``text`` to the forge's body limit, saying so at the end."""
    if len(text) <= max_length:
        return text
    if max_length <= len(TRUNCATION_NOTE):
        return text[:max_length]
    return text[: max_length - len(TRUNCATION_NOTE)] + TRUNCATION_NOTE


def slugify(title: str, max_len: int = 30) -> str:
    slug = title.lower()
    slug = re.sub(r"[^a-z0-9]+", "-", slug)
    slug = slug.strip("-")
    return slug[:max_len].strip("-")


def branch_name(
    issue_number: int,
    title: str,
    workflow: str,
    branch_prefix: str,
    base_branch: str,
    *,
    slug_max_length: int,
) -> str:
    slug = slugify(title, max_len=slug_max_length)
    if workflow == "gitflow":
        return f"{base_branch}-{slug}"
    return f"{branch_prefix}/issue-{issue_number}-{slug}"


def commit_message(issue_ref: str, description: str, author_login: str) -> str:
    return f"fix({issue_ref}): {description}\n\nCo-authored-by: {author_login}"


def pr_title(issue_ref: str, description: str) -> str:
    return f"[agent] fix({issue_ref}): {description}"


def pr_body(
    *,
    issue_ref: str,
    closing_reference: str | None,
    task_id: str,
    description: str,
    files_changed: list[tuple[str, str]] | None = None,
    cost_usd: float = 0.0,
    iterations: int = 0,
    testing_notes: str | None = None,
    reviewer_notes: str | None = None,
    agent_name: str = "",
) -> str:
    """``closing_reference`` is None when the forge can't be trusted to
    auto-close the issue; the body then names the issue without promising
    it will close."""
    parts: list[str] = [
        f"## Issue\n{closing_reference or issue_ref}",
        f"## Summary\n{description}",
    ]

    if files_changed:
        files_lines = "\n".join(f"- `{path}` — {reason}" for path, reason in files_changed)
        parts.append(f"## Files changed\n{files_lines}")

    if testing_notes:
        parts.append(f"## How I tested\n{testing_notes}")

    if reviewer_notes:
        parts.append(f"## Reviewer notes\n{reviewer_notes}")

    parts.append(
        f"---\n"
        f"🤖 Generated by {agent_name} (mini-SWE-agent v2).\n"
        f"Task ID: `{task_id}`. Cost: ${cost_usd:.2f}. Iterations: {iterations}."
    )

    return "\n\n".join(parts)
