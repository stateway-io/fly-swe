def _pull(number: int, head: str) -> MagicMock:
    pr = MagicMock(spec=PullRequest)
    pr.number = number
    pr.html_url = f"https://github.com/{REPO}/pull/{number}"
    pr.head.ref = head
    return pr


class TestCreatePR:
    def test_creates_and_labels(self, pulls: GitHubPullRequestClient, client: MagicMock) -> None:
        client.create_pr.return_value = _pull(99, "agent/issue-42-fix-typo")
        issue = client.get_repo.return_value.get_issue.return_value

        pr = pulls.create_pr(
            head="agent/issue-42-fix-typo",
            base="main",
            title="[agent] fix(#42): Fix typo",
            body="## Summary\nFixed a typo.",
            draft=False,
            labels=[],
        )

        assert pr == PRRef(
            number=99,
            url=f"https://github.com/{REPO}/pull/99",
            head_ref="agent/issue-42-fix-typo",
        )
        client.create_pr.assert_called_once_with(
            full_name=REPO,
            title="[agent] fix(#42): Fix typo",
            body="## Summary\nFixed a typo.",
            head="agent/issue-42-fix-typo",
            base="main",
            draft=False,
        )
        client.get_repo.assert_called_once_with(REPO)
        client.get_repo.return_value.get_issue.assert_called_once_with(99)
        issue.add_to_labels.assert_called_once_with("agent-generated")

    def test_draft_with_extra_labels(
        self, pulls: GitHubPullRequestClient, client: MagicMock
    ) -> None:
        """A gitflow/draft route must reach the API call and the label call,
        not be accepted and silently dropped."""
        client.create_pr.return_value = _pull(100, "dev-fix-typo")
        issue = client.get_repo.return_value.get_issue.return_value

        pulls.create_pr(
            head="dev-fix-typo",
            base="dev",
            title="t",
            body="b",
            draft=True,
            labels=["needs-review"],
        )

        assert client.create_pr.call_args.kwargs["draft"] is True
        assert client.create_pr.call_args.kwargs["base"] == "dev"
        issue.add_to_labels.assert_called_once_with("agent-generated", "needs-review")


class TestFindOpenPR:
    def test_existing_pr_on_the_branch(
        self, pulls: GitHubPullRequestClient, client: MagicMock
    ) -> None:
        client.find_pr_by_branch.return_value = _pull(7, "agent/issue-42-fix-typo")

        pr = pulls.find_open_pr("agent/issue-42-fix-typo")

        assert pr is not None and pr.number == 7
        client.find_pr_by_branch.assert_called_once_with(REPO, "agent/issue-42-fix-typo")
        client.create_pr.assert_not_called()

    def test_refuses_an_existing_pr_on_another_branch(
        self, pulls: GitHubPullRequestClient, client: MagicMock
    ) -> None:
        """A PR whose head is not the work branch belongs to another issue.
        Reporting it made the run comment "opened a PR" while abandoning its
        own commits (issue #89) — it has to be a hard failure instead."""
        client.find_pr_by_branch.return_value = _pull(244, "dev-some-other-issue")

        with pytest.raises(PRHeadMismatchError) as exc:
            pulls.find_open_pr("agent/issue-42-fix-typo")

        assert "244" in str(exc.value)
        assert "agent/issue-42-fix-typo" in str(exc.value)


class TestPRHasConflicts:
    """Read after a follow-up's push: only a definite answer for the commit
    just pushed may turn into a "still conflicting" warning."""

    _PR = PRRef(number=1, url="u", head_ref="b")

    @staticmethod
    def _state(sha: str, mergeable: bool | None) -> MagicMock:
        pr = MagicMock()
        pr.head.sha = sha
        pr.mergeable = mergeable
        return pr

    def test_conflicting_pr(self, pulls: GitHubPullRequestClient, client: MagicMock) -> None:
        client.get_pull_request.side_effect = [self._state("abc", False)]
        assert pulls.pr_has_conflicts(self._PR, "abc") is True

    def test_mergeable_pr(self, pulls: GitHubPullRequestClient, client: MagicMock) -> None:
        client.get_pull_request.side_effect = [self._state("abc", True)]
        assert pulls.pr_has_conflicts(self._PR, "abc") is False

    def test_waits_for_the_pushed_head_and_a_computed_answer(
        self, pulls: GitHubPullRequestClient, client: MagicMock
    ) -> None:
        client.get_pull_request.side_effect = [
            self._state("old", False),  # stale answer for the previous head
            self._state("abc", None),  # still computing
            self._state("abc", True),
        ]
        assert pulls.pr_has_conflicts(self._PR, "abc") is False
        assert client.get_pull_request.call_count == 3

    def test_unknown_after_all_attempts(
        self, pulls: GitHubPullRequestClient, client: MagicMock
    ) -> None:
        client.get_pull_request.return_value = self._state("abc", None)
        assert pulls.pr_has_conflicts(self._PR, "abc") is None
        assert client.get_pull_request.call_count == 5

    def test_api_error_is_unknown(self, pulls: GitHubPullRequestClient, client: MagicMock) -> None:
        client.get_pull_request.side_effect = RuntimeError("boom")
        assert pulls.pr_has_conflicts(self._PR, "abc") is None
