class TestGitHubPRText:
    """The text the core builds from GitHub's references."""

    def test_commit_message(self, transport: GitHubTransport) -> None:
        ref = transport.format_ref("issue", 42, repo="owner/repo", from_repo="owner/repo")
        msg = pr_text.commit_message(ref, "Fix typo in README", "johndoe")
        assert msg == "fix(#42): Fix typo in README\n\nCo-authored-by: johndoe"

    def test_commit_message_author_with_email(self) -> None:
        msg = pr_text.commit_message("#7", "Update deps", "bob <bob@example.com>")
        assert "Co-authored-by: bob <bob@example.com>" in msg

    def test_cross_repo_commit_qualifies_the_issue(self, transport: GitHubTransport) -> None:
        ref = transport.format_ref("issue", 42, repo="owner/issues", from_repo="owner/code")
        msg = pr_text.commit_message(ref, "Fix typo in README", "johndoe")
        assert msg.startswith("fix(owner/issues#42): Fix typo in README")

    def test_pr_title(self) -> None:
        assert (
            pr_text.pr_title("#42", "Fix typo in README") == "[agent] fix(#42): Fix typo in README"
        )

    def test_pr_title_multiline_description(self) -> None:
        assert pr_text.pr_title("#1", "Fix\nsomething") == "[agent] fix(#1): Fix\nsomething"

    def test_minimal_body_closes_the_issue(self, transport: GitHubTransport) -> None:
        body = pr_text.pr_body(
            issue_ref="#42",
            closing_reference=transport.closing_reference("owner/repo", 42, "owner/repo"),
            task_id="task-1",
            description="Fixed a typo in the README.",
        )
        assert "Closes #42" in body
        assert "Fixed a typo in the README." in body
        assert "task-1" in body
        assert "Cost: $0.00" in body
        assert "Iterations: 0" in body

    def test_cross_repo_body_closes_the_qualified_issue(self, transport: GitHubTransport) -> None:
        """An unqualified `Closes #N` would point GitHub's auto-close
        at issue #N of the target repo instead of the issue repo."""
        body = pr_text.pr_body(
            issue_ref="owner/issues#42",
            closing_reference=transport.closing_reference("owner/issues", 42, "owner/code"),
            task_id="task-1",
            description="Fixed",
        )
        assert "Closes owner/issues#42" in body


class TestPRBodySections:
    @staticmethod
    def _body(**overrides) -> str:
        fields = dict(
            issue_ref="#42",
            closing_reference="Closes #42",
            task_id="t1",
            description="Fixed",
        )
        fields.update(overrides)
        return pr_text.pr_body(**fields)

    def test_headers_are_english(self) -> None:
        body = self._body(
            files_changed=[("README.md", "Fix the typo")],
            testing_notes="- [x] `pytest` passed",
            reviewer_notes="Check the edge case",
        )
        for header in ("## Summary", "## Files changed", "## How I tested", "## Reviewer notes"):
            assert header in body
        for portuguese in (
            "Resumo da mudança",
            "Arquivos alterados",
            "Como testei",
            "Notas para o revisor",
        ):
            assert portuguese not in body

    def test_uses_configured_agent_name(self) -> None:
        body = self._body(agent_name="My Custom Bot")
        assert "Generated by My Custom Bot" in body
        assert "Stateway" not in body

    def test_with_files_changed(self) -> None:
        body = self._body(
            files_changed=[("README.md", "Fix the typo"), ("docs/index.md", "Fix another")]
        )
        assert "`README.md`" in body
        assert "`docs/index.md`" in body

    def test_with_cost_and_iterations(self) -> None:
        body = self._body(cost_usd=1.50, iterations=10)
        assert "$1.50" in body
        assert "Iterations: 10" in body

    def test_with_testing_and_reviewer_notes(self) -> None:
        body = self._body(
            testing_notes="- [x] `npm test` passed",
            reviewer_notes="Check the edge case on line 42",
        )
        assert "npm test" in body
        assert "edge case" in body


